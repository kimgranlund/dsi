import { canonicalNameOf, parseConcept, type Ontology } from '@dsi/schema';
import { resolveConcept, showValue, type ConceptAnswer, type MappingSet, type NativeSet } from '@dsi/resolve';

export const EXT = 'io.nonoun.dsi';

/**
 * Canonical token name from a compositional concept: the facet values in the concept's fixed facet order, joined by
 * '-' ('+' combinations kept). Facet values are unique across facets, so the name is unambiguous; the concept IRI in
 * $extensions stays the identity. dsi:concept/color/intent-danger/property-text -> color / "danger-text".
 */
export function canonicalName(o: Ontology, concept: string): { group: string; name: string } | undefined {
  const p = parseConcept(o, concept);
  if (typeof p === 'string') return undefined;
  return { group: p.domain, name: canonicalNameOf(p) };
}

export interface ProductInput { set: NativeSet; maps: MappingSet; name: string }

export interface CanonCell { status: ConceptAnswer['status']; token?: string; match?: string; via?: string; value?: string }
export interface CanonResult {
  concepts: { concept: string; group: string; name: string; label: string }[];
  /** product -> mode -> token tree (DTCG). Concepts a product cannot answer are omitted, never filled in. */
  files: Map<string, { product: string; mode: string; theme: string; tree: Record<string, Record<string, unknown>>; css: string }>;
  /** concept -> product -> mode -> cell */
  coverage: Record<string, Record<string, Record<string, CanonCell>>>;
}

/**
 * Build the canonical set: every compositional concept with at least one approved, non-related mapping in any
 * product; for each product and declared mode, resolve every concept through @dsi/resolve (match / nearest / absent /
 * unknown) and emit the answering token's resolved value. Nearest answers are flagged in $extensions.
 */
export function buildCanon(o: Ontology, labels: Map<string, string>, products: ProductInput[]): CanonResult {
  const used = new Set<string>();
  for (const p of products) for (const m of p.maps.mappings) if (m.status === 'approved' && m.match !== 'related' && m.concept.startsWith('dsi:concept/')) used.add(m.concept);
  const concepts = [...used].sort().flatMap((c) => {
    const n = canonicalName(o, c);
    if (!n) return [];
    const p = parseConcept(o, c) as Exclude<ReturnType<typeof parseConcept>, string>;
    const label = Object.entries(p.facets).map(([f, v]) => String(v).split('+').map((x) => labels.get(`dsi:${f}/${x}`) ?? x).join(' + ')).join(' · ');
    return [{ concept: c, ...n, label }];
  });
  const seen = new Map<string, string>();
  for (const c of concepts) { const k = `${c.group}.${c.name}`; if (seen.has(k)) throw new Error(`canonical name ${k} is shared by ${seen.get(k)} and ${c.concept}`); seen.set(k, c.concept); }

  const files: CanonResult['files'] = new Map();
  const coverage: CanonResult['coverage'] = {};
  for (const { set, maps, name } of products) {
    const modes = Object.keys(set.modes).length ? set.modes : { light: '' };
    for (const [mode, theme] of Object.entries(modes)) {
      const tree: Record<string, Record<string, unknown>> = {};
      const css: string[] = [];
      for (const c of concepts) {
        const a = resolveConcept(o, set, maps, c.concept, mode);
        const cell: CanonCell = { status: a.status };
        if (a.answer && (a.status === 'match' || a.status === 'nearest') && a.answer.value !== undefined) {
          const ans = a.answer;
          Object.assign(cell, { token: ans.token, match: ans.match, via: ans.via, value: ans.display });
          const native = set.tokens.get(ans.token);
          (tree[c.group] ??= {})[c.name] = {
            $type: ans.type ?? 'color',
            $value: ans.value,
            $description: c.label,
            $extensions: { [EXT]: { concept: c.concept, product: set.product, version: set.version, mode, theme: theme || undefined, token: ans.token, nativeName: native?.prov.nativeName, status: a.status, match: ans.match, via: ans.via, ...(a.note ? { note: a.note } : {}) } },
          };
          const nn = String(native?.prov.nativeName ?? '');
          css.push(`  --dsi-${c.group}-${c.name.replaceAll('+', '_')}: ${nn.startsWith('--') ? `var(${nn}, ${ans.display.split(' @ ')[0]})` : ans.display.split(' @ ')[0]};${a.status === 'nearest' ? ' /* nearest: ' + ans.match + ' */' : ''}`);
        }
        ((coverage[c.concept] ??= {})[set.product] ??= {})[mode] = cell;
      }
      const header = `/* ${name} ${set.version}, canonical tokens in ${mode} mode${theme ? ` (theme ${theme})` : ''}. Generated by @dsi/canon; do not edit. */`;
      files.set(`${set.product}.${mode}`, { product: set.product, mode, theme, tree, css: `${header}\n:root {\n${css.join('\n')}\n}\n` });
    }
  }
  return { concepts, files, coverage };
}
