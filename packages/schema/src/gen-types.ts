import fs from 'node:fs';
import path from 'node:path';
import { compile } from 'json-schema-to-typescript';
import { SCHEMA_DIR } from './validate.ts';

// Generated, never hand-edited: the JSON Schemas are the single authority.
const out = path.join(SCHEMA_DIR, '..', 'src', 'generated');
fs.mkdirSync(out, { recursive: true });
const parts: string[] = ['/* Generated by src/gen-types.ts from schemas/. Do not edit. */'];
for (const f of ['catalog-entry', 'source', 'mapping-file', 'dtcg-extension']) {
  const schema = JSON.parse(fs.readFileSync(path.join(SCHEMA_DIR, `${f}.schema.json`), 'utf8'));
  parts.push(await compile(schema, schema.title, { bannerComment: '', cwd: SCHEMA_DIR, declareExternallyReferenced: true, $refOptions: { resolve: { http: false, dsi: { order: 1, canRead: /^https:\/\/dsi\.nonoun\.io\/schema\//, read: (file: { url: string }) => fs.readFileSync(path.join(SCHEMA_DIR, path.basename(file.url)), 'utf8') } } } as never }));
}
fs.writeFileSync(path.join(out, 'types.ts'), parts.join('\n'));
console.log('wrote src/generated/types.ts');
